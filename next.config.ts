import type { NextConfig } from "next";

// Baseline security headers. No CSP yet: inline styles from Tailwind's
// runtime-free output are fine, but Next's own inline bootstrapping scripts
// would need nonces; deferred until there is a threat model that needs it.
const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "X-Frame-Options", value: "DENY" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=()",
  },
];

const nextConfig: NextConfig = {
  async headers() {
    return [{ source: "/(.*)", headers: securityHeaders }];
  },
};

export default nextConfig;
